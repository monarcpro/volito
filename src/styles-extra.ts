/** A style's prose, with words for the package's patterns (the engine only knows its own textures). */
export function styleBody(s: Source | BrandStyle): string {
  const word = (PATTERN_WORDS as Record<string, string>)[s.texture];
  if (!word) return defaultStyleBody(s as BrandStyle);
  return defaultStyleBody({ ...s, texture: "none" } as BrandStyle).replace("clean grounds, no texture", word);
}

/** The extra styles as full BrandStyles (body written from the tokens). */
export const MOTION_STYLES: BrandStyle[] = SOURCES.map((s) => ({ ...s, texture: s.texture as BrandTexture, body: styleBody(s), source: "builtin" as const }));
